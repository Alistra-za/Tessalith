"""Generates crates/bcenc/src/bc1/tables.rs from the vendored rgbcx text.

  py -3.13 -I tools/gen-bcenc-tables.py <rgbcx.cpp> <rgbcx_table4.h> <tables.rs>

Reads the initialiser lists of g_unique_total_orders4, g_unique_total_orders3 and g_best_total_orderings3 from
rgbcx.cpp and of g_best_total_orderings4 from rgbcx_table4.h (the large table: RGBCX_USE_SMALLER_TABLES is 0), and
writes them as Rust statics. Deterministic: running it twice writes the same bytes (LF line ends). The tests in
crates/bcenc/tests/bc1_tables.rs compare the statics with the vendored text again, by their own parser.
"""
import re
import sys


def initialiser(text, marker):
    at = text.index(marker)
    start = text.index("=", at) + 1
    return text[start : text.index("};", start)]


def groups(text):
    """Every innermost {a,b,..} group, as a list of ints."""
    out = []
    for piece in text.split("}"):
        if "{" not in piece:
            continue
        body = piece[piece.rindex("{") + 1 :]
        out.append([int(x) for x in body.split(",") if x.strip()])
    return out


def constant(text, name):
    m = re.search(r"uint32_t\s+" + name + r"\s*=\s*(\d+)\s*;", text)
    assert m, name
    return int(m.group(1))


def rows(name, ty, width, data):
    lines = ["#[rustfmt::skip]", f"pub static {name}: [[{ty}; {width}]; N{name[-1]}] = ["]
    for g in data:
        assert len(g) == width, (name, len(g), width)
        lines.append("    [" + ", ".join(str(v) for v in g) + "],")
    lines.append("];")
    return lines


def main():
    cpp_path, table4_path, out_path = sys.argv[1:4]
    with open(cpp_path, encoding="utf-8", newline="") as f:
        cpp = f.read()
    with open(table4_path, encoding="utf-8", newline="") as f:
        table4 = f.read()

    n4 = constant(cpp, "NUM_UNIQUE_TOTAL_ORDERINGS4")
    n3 = constant(cpp, "NUM_UNIQUE_TOTAL_ORDERINGS3")
    u4 = groups(initialiser(cpp, "g_unique_total_orders4["))
    u3 = groups(initialiser(cpp, "g_unique_total_orders3["))
    b3 = groups(initialiser(cpp, "g_best_total_orderings3["))
    b4 = groups(table4)
    max4 = len(b4[0])

    assert len(u4) == n4 and len(b4) == n4, (len(u4), len(b4), n4)
    assert len(u3) == n3 and len(b3) == n3, (len(u3), len(b3), n3)
    assert all(len(g) == max4 for g in b4)
    assert all(sum(g) == 16 for g in u4) and all(sum(g) == 16 for g in u3)
    assert all(v < n4 for g in b4 for v in g) and all(v < n3 for g in b3 for v in g)
    assert all(v < 256 for g in b3 for v in g) and all(v < 65536 for g in b4 for v in g)

    out = [
        "// Generated by tools/gen-bcenc-tables.py from crates/encoders-sys/vendor/bc7enc_rdo/rgbcx.cpp and",
        "// rgbcx_table4.h (bc7enc_rdo commit b943862); generated, do not edit. Regenerate with:",
        "//   py -3.13 -I tools/gen-bcenc-tables.py <rgbcx.cpp> <rgbcx_table4.h> crates/bcenc/src/bc1/tables.rs",
        "// The tests in tests/bc1_tables.rs compare every entry with the vendored text.",
        "",
        "/// `NUM_UNIQUE_TOTAL_ORDERINGS4`.",
        f"pub const N4: usize = {n4};",
        "/// `NUM_UNIQUE_TOTAL_ORDERINGS3`.",
        f"pub const N3: usize = {n3};",
        "/// `MAX_TOTAL_ORDERINGS4` (the large table).",
        f"pub const MAX_TOTAL_ORDERINGS4: usize = {max4};",
        "",
        "/// `g_unique_total_orders4`: selector histograms of 4-colour blocks, in linear selector order.",
        *rows("UNIQUE_TOTAL_ORDERS4", "u8", 4, u4),
        "",
        "/// `g_unique_total_orders3`: selector histograms of 3-colour blocks.",
        *rows("UNIQUE_TOTAL_ORDERS3", "u8", 3, u3),
        "",
        "/// `g_best_total_orderings4`: for each 4-colour ordering, the orderings worth trying, best first.",
        *rows("BEST_TOTAL_ORDERINGS4", "u16", max4, b4),
        "",
        "/// `g_best_total_orderings3`: the same for 3-colour orderings.",
        *rows("BEST_TOTAL_ORDERINGS3", "u8", 32, b3),
    ]
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


main()
